/** Translate a UI key for a language id, with {var} interpolation and English fallback. */
export function translate(langId, key, vars) {
  const str = UI[langId]?.[key] ?? UI.en[key] ?? key;
  if (!vars) return str;
  return str.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? String(vars[k]) : m));
}
